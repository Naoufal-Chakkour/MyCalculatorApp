function buildSearchIndex() {
    const index = [];
    STAGES.forEach((st, si) => {
        st.years.forEach((yr, yi) => {
            yr.lessons.forEach((lesson, li) => {
                let text = (lesson.keywords || '');
                text += ' ' + (lesson.intro || []).join(' ');
                text += ' ' + (lesson.theory ? lesson.theory.points.join(' ') : '');
                text += ' ' + (lesson.formulas || []).join(' ');
                text += ' ' + (lesson.examples || []).map(e => e.question + ' ' + (e.solution || []).join(' ')).join(' ');
                index.push({ si: si, yi: yi, li: li, stage: st, year: yr, title: lesson.title, text: text.toLowerCase() });
            });
        });
    });
    return index;
}

function onSearchInput() {
    const box = document.getElementById('searchResults');
    const q = document.getElementById('searchInput').value.trim().toLowerCase();
    if (!q) {
        box.classList.remove('open');
        box.innerHTML = '';
        return;
    }
    const matches = SEARCH_INDEX
        .filter(e => e.title.toLowerCase().includes(q) || e.text.includes(q))
        .slice(0, 8);
    if (!matches.length) {
        box.innerHTML = '<div class="sr-empty">لا توجد نتائج مطابقة</div>';
    } else {
        box.innerHTML = matches.map(m =>
            '<button class="sr-item" data-sr="' + m.si + '|' + m.yi + '|' + m.li + '">'
            + '<span class="sr-level" style="--lc:' + m.stage.color + '">' + m.stage.short + '</span>'
            + '<span>' + m.year.title + ' · ' + m.title + '</span></button>'
        ).join('');
    }
    box.classList.add('open');
}

function onSidebarClick(e) {
    const navBtn = e.target.closest('[data-nav]');
    if (navBtn) {
        const parts = navBtn.dataset.nav.split('|');
        if (parts[0] === 'stages') renderSidebar();
        else if (parts[0] === 'stage') renderSidebarYears(parts[1]);
        else if (parts[0] === 'year') renderSidebarLessons(parts[1], parseInt(parts[2], 10));
        return;
    }
    const lessonBtn = e.target.closest('.lesson-btn');
    if (lessonBtn) {
        openLesson(lessonBtn.dataset.stage, parseInt(lessonBtn.dataset.year, 10), parseInt(lessonBtn.dataset.idx, 10));
    }
}

function onContentClick(e) {
    const opener = e.target.closest('[data-open]');
    if (!opener) return;
    const parts = opener.dataset.open.split('|');
    openLesson(parts[0], parseInt(parts[1], 10), parseInt(parts[2], 10));
}

function onSearchResultClick(e) {
    const item = e.target.closest('.sr-item');
    if (!item) return;
    const parts = item.dataset.sr.split('|');
    document.getElementById('searchInput').value = '';
    document.getElementById('searchResults').classList.remove('open');
    openLesson(STAGES[parseInt(parts[0], 10)].id, parseInt(parts[1], 10), parseInt(parts[2], 10));
}

