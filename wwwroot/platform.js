function formulaBlock(lesson) {
    if (!lesson.formulas || !lesson.formulas.length) return '';
    return '<div class="formula-box"><ul>'
        + lesson.formulas.map(f => '<li><span class="formula">' + f + '</span></li>').join('')
        + '</ul></div>';
}

function theoryBlock(lesson) {
    if (!lesson.theory) return '';
    return '<div class="theorem-box"><div class="theorem-title">'
        + (lesson.theory.title || 'القاعدة الأساسية')
        + '</div><ul>'
        + lesson.theory.points.map(p => '<li>' + p + '</li>').join('')
        + '</ul></div>';
}

function examplesBlock(lesson) {
    if (!lesson.examples || !lesson.examples.length) return '';
    const cards = lesson.examples.map((ex, i) =>
        '<div class="example-card"><div class="example-title">مثال ' + (i + 1) + '</div>'
        + '<div class="example-question">' + ex.question + '</div>'
        + '<div class="example-solution">'
        + ex.solution.map(s => '<p>' + s + '</p>').join('')
        + '</div></div>'
    ).join('');
    return '<h2 class="section-title">أمثلة محلولة</h2>' + cards;
}

function calcButtons(lesson) {
    if (!lesson.calcs || !lesson.calcs.length) return '';
    const btns = lesson.calcs.map(c => {
        let url = 'calculator.html?tab=' + encodeURIComponent(c.tab || 'calc');
        if (c.expr) url += '&expr=' + encodeURIComponent(c.expr);
        if (c.a !== undefined && c.a !== null && c.a !== '') url += '&a=' + encodeURIComponent(c.a);
        if (c.b !== undefined && c.b !== null && c.b !== '') url += '&b=' + encodeURIComponent(c.b);
        if (c.c !== undefined && c.c !== null && c.c !== '') url += '&c=' + encodeURIComponent(c.c);
        return '<a class="calc-cta" href="' + url + '">' + (c.label || 'جرّبها في الآلة الحاسبة') + '</a>';
    });
    return '<div class="calc-actions">' + btns.join('') + '</div>';
}

function lessonNav(stage, yearIdx, idx) {
    const yr = stage.years[yearIdx];
    let nav = '<div class="lesson-nav">';
    if (idx > 0) {
        nav += '<button class="nav-btn" onclick="openLesson(\'' + stage.id + '\',' + yearIdx + ',' + (idx - 1) + ')">السابق: ' + yr.lessons[idx - 1].title + '</button>';
    }
    nav += '<button class="nav-btn nav-home" onclick="renderHome()">العودة إلى الرئيسية</button>';
    if (idx < yr.lessons.length - 1) {
        nav += '<button class="nav-btn" onclick="openLesson(\'' + stage.id + '\',' + yearIdx + ',' + (idx + 1) + ')">التالي: ' + yr.lessons[idx + 1].title + '</button>';
    }
    nav += '</div>';
    return nav;
}

function buildLessonHTML(stage, year, lesson, idx) {
    const intro = (lesson.intro || []).map(p => '<p>' + p + '</p>').join('');
    const yi = yearIdxOf(STAGES, stage.id, year.title);
    return '<nav class="breadcrumb"><button onclick="renderHome()">رئيسية</button> <span>/</span> <span>'
        + stage.title + '</span> <span>/</span> <span>' + year.title + '</span> <span>/</span> <span>' + lesson.title + '</span></nav>'
        + '<h1 class="lesson-title">' + lesson.title + '</h1>'
        + '<div class="level-chip" style="--lc:' + stage.color + '">' + stage.short + ' · ' + year.title + ' · الدرس ' + (idx + 1) + '</div>'
        + intro
        + explainBlock(lesson)
        + visualBlock(stage, year, lesson)
        + photoBlock(stage, year, lesson)
        + formulaBlock(lesson)
        + theoryBlock(lesson)
        + examplesBlock(lesson)
        + practiceBlock(lesson)
        + seriesBlock(stage.id, yi, idx, lesson)
        + calcButtons(lesson)
        + lessonNav(stage, yi, idx);
}

function yearIdxOf(stages, stageId, yearTitle) {
    const si = stageById(stageId);
    const years = stages[si].years;
    for (let i = 0; i < years.length; i++) {
        if (years[i].title === yearTitle) return i;
    }
    return 0;
}

function openLesson(stageId, yearIdx, lessonIdx) {
    const si = stageById(stageId);
    const stage = STAGES[si];
    const year = stage.years[yearIdx];
    if (!year) return;
    const lesson = year.lessons[lessonIdx];
    if (!lesson) return;

    document.getElementById('content').innerHTML = buildLessonHTML(stage, year, lesson, lessonIdx);

    renderSidebarLessons(stageId, yearIdx);
    const btn = document.querySelector('.lesson-btn[data-stage="' + stageId + '"][data-year="' + yearIdx + '"][data-idx="' + lessonIdx + '"]');
    if (btn) btn.classList.add('active');
    const snav = document.getElementById('sidebar');
    if (snav) snav.scrollTop = 0;
    closeSidebar();
    document.title = lesson.title + ' — ' + year.title + ' | منصة الرياضيات';
    window.scrollTo({ top: 0, behavior: 'smooth' });
}

function renderSidebarYears(stageId) {
    const si = stageById(stageId);
    const st = STAGES[si];
    const nav = document.getElementById('sidebar');
    let html = '<div class="sidebar-nav-top">'
        + '<button class="nav-back" data-nav="stages">↩ كل المراحل</button>'
        + '</div>'
        + '<div class="sidebar-nav-title" style="--lc:' + st.color + '">' + st.title + ' — اختر السنة</div>';
    st.years.forEach((yr, yi) => {
        html += '<button class="year-card" data-nav="year|' + st.id + '|' + yi + '" style="--lc:' + st.color + '">'
            + '<span class="year-num">' + (yi + 1) + '</span>'
            + '<span class="year-name">' + yr.title + '</span>'
            + '<span class="year-count">' + yr.lessons.length + '</span>'
            + '</button>';
    });
    html += '<div class="sidebar-hint">اختر السنة لعرض دروسها فقط.</div>';
    nav.innerHTML = html;
}

function renderSidebarLessons(stageId, yearIdx) {
    const si = stageById(stageId);
    const st = STAGES[si];
    const yr = st.years[yearIdx];
    if (!yr) {
        renderSidebar();
        return;
    }
    const nav = document.getElementById('sidebar');
    let html = '<div class="sidebar-nav-top">'
        + '<button class="nav-back" data-nav="stages">↩ كل المراحل</button>'
        + '<button class="nav-back" data-nav="stage|' + stageId + '">↩ السنوات</button>'
        + '</div>'
        + '<div class="sidebar-nav-title" style="--lc:' + st.color + '">' + yr.title + '</div>'
        + '<ul class="year-lessons sidebar-lessons">';
    yr.lessons.forEach((l, li) => {
        html += '<li><button class="lesson-btn" data-stage="' + stageId + '" data-year="' + yearIdx + '" data-idx="' + li + '">'
            + (li + 1) + '. ' + l.title + '</button></li>';
    });
    html += '</ul>';
    nav.innerHTML = html;
}

function extrasFor(lesson) {
    return EXTRA_DATA[lesson.title] || null;
}

function explainBlock(lesson) {
    const ex = extrasFor(lesson);
    if (!ex || !ex.explain) return '';
    return '<section class="explain-block"><h3>الشرح الموسّع</h3><p>' + ex.explain + '</p></section>';
}

function photoBlock(stage, year, lesson) {
    const hay = stage.id + ' ' + year.title + ' ' + lesson.title + ' ' + (lesson.keywords || '');
    for (let i = 0; i < PHOTOS_DATA.length; i++) {
        const p = PHOTOS_DATA[i];
        const terms = p.terms || [];
        for (let t = 0; t < terms.length; t++) {
            if (hay.indexOf(terms[t]) !== -1) {
                const href = p.src.split('?')[0];
                return '<figure class="lesson-photo"><a href="' + href + '" target="_blank" rel="noopener" title="اضغط لعرض الصورة كاملة">'
                    + '<img src="' + p.src + '" loading="lazy" alt="' + p.cap + '" onerror="this.parentNode.parentNode.style.display=\'none\'">'
                    + '</a><figcaption>' + p.cap + '</figcaption></figure>';
            }
        }
    }
    return '';
}

