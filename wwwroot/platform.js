function pieSlice(cx, cy, r, a0, a1) {
    const p0 = polar(cx, cy, r, a0), p1 = polar(cx, cy, r, a1);
    const large = (a1 - a0 > Math.PI) ? 1 : 0;
    return 'M' + cx + ' ' + cy + 'L' + p0[0].toFixed(1) + ' ' + p0[1].toFixed(1)
        + 'A' + r + ' ' + r + ' 0 ' + large + ' 1 ' + p1[0].toFixed(1) + ' ' + p1[1].toFixed(1) + 'Z';
}

function graphPoints(f, minX, maxX, n) {
    const pts = [];
    const step = (maxX - minX) / n;
    for (let k = 0; k <= n; k++) {
        const x = minX + step * k;
        const y = f(x);
        if (y === null || y === undefined || !isFinite(y)) continue;
        pts.push([x, y]);
    }
    return pts;
}

function pathFrom(pts, px, py) {
    let d = '';
    for (const p of pts) {
        d += (d ? 'L' : 'M') + px(p[0]).toFixed(1) + ' ' + py(p[1]).toFixed(1);
    }
    return d;
}

function visGraph(curves, caption, opts) {
    opts = opts || {};
    const minX = (opts.minX === undefined) ? -5 : opts.minX;
    const maxX = (opts.maxX === undefined) ? 5 : opts.maxX;
    const minY = (opts.minY === undefined) ? -3 : opts.minY;
    const maxY = (opts.maxY === undefined) ? 5 : opts.maxY;
    const w = 380, h = 250, pl = 44, pr = 16, pt = 14, pb = 30;
    const px = x => pl + ((x - minX) / (maxX - minX)) * (w - pl - pr);
    const py = y => pt + (1 - (y - minY) / (maxY - minY)) * (h - pt - pb);
    let svg = '<svg viewBox="0 0 ' + w + ' ' + h + '" role="img" aria-label="رسم بياني">';
    for (let i = Math.ceil(minX); i <= Math.floor(maxX); i++) {
        svg += '<line x1="' + px(i).toFixed(1) + '" y1="' + pt + '" x2="' + px(i).toFixed(1) + '" y2="' + (h - pb) + '" stroke="' + VCOL.grid + '" stroke-width="1"/>';
    }
    for (let i = Math.ceil(minY); i <= Math.floor(maxY); i++) {
        svg += '<line x1="' + pl + '" y1="' + py(i).toFixed(1) + '" x2="' + (w - pr) + '" y2="' + py(i).toFixed(1) + '" stroke="' + VCOL.grid + '" stroke-width="1"/>';
    }
    const xAxisY = py(0).toFixed(1), yAxisX = px(0).toFixed(1);
    svg += '<line x1="' + pl + '" y1="' + xAxisY + '" x2="' + (w - pr) + '" y2="' + xAxisY + '" stroke="' + VCOL.line + '" stroke-width="2"/>';
    svg += '<line x1="' + yAxisX + '" y1="' + pt + '" x2="' + yAxisX + '" y2="' + (h - pb) + '" stroke="' + VCOL.line + '" stroke-width="2"/>';
    for (let i = Math.ceil(minX); i <= Math.floor(maxX); i++) {
        if (i === 0) continue;
        svg += '<text x="' + px(i).toFixed(1) + '" y="' + (parseFloat(xAxisY) + 16) + '" text-anchor="middle" fill="#9aa0b0" font-size="11">' + i + '</text>';
    }
    for (let i = Math.ceil(minY); i <= Math.floor(maxY); i++) {
        if (i === 0) continue;
        svg += '<text x="' + (parseFloat(yAxisX) - 6) + '" y="' + (parseFloat(py(i).toFixed(1)) + 4) + '" text-anchor="end" fill="#9aa0b0" font-size="11">' + i + '</text>';
    }
    if (opts.shade && curves.length) {
        const c0 = curves[0];
        const pts = graphPoints(c0.fn, opts.shade[0], opts.shade[1], 120);
        let d = 'M' + px(opts.shade[0]).toFixed(1) + ' ' + xAxisY;
        pts.forEach(p => { d += 'L' + px(p[0]).toFixed(1) + ' ' + py(p[1]).toFixed(1); });
        d += 'L' + px(opts.shade[1]).toFixed(1) + ' ' + xAxisY + 'Z';
        svg += '<path d="' + d + '" fill="' + VCOL.teal + '" fill-opacity="0.22" stroke="none"/>';
    }
    (curves || []).forEach(c => {
        const pts = graphPoints(c.fn, minX, maxX, 240);
        const d = pathFrom(pts, px, py);
        let extra = '';
        if (c.dash) extra = ' stroke-dasharray="6 5"';
        if (d) svg += '<path d="' + d + '" fill="none" stroke="' + (c.color || VCOL.teal) + '" stroke-width="' + (c.width || 3) + '"' + extra + '/>';
    });
    (opts.points || []).forEach(p => {
        svg += '<circle cx="' + px(p.x).toFixed(1) + '" cy="' + py(p.y).toFixed(1) + '" r="5" fill="' + (p.color || VCOL.amber) + '" stroke="#0b0b18" stroke-width="1.5"/>';
    });
    svg += '</svg>';
    return visFig(svg, caption);
}

